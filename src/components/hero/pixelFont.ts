/** A 5 × 7 block alphabet for the hero sculpture: only the letters MAVERN and the medium words use. */
export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const GAP = 1;

const glyphs: Record<string, string[]> = {
  A: [".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"],
  B: ["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."],
  E: ["#####", "#....", "#....", "####.", "#....", "#....", "#####"],
  F: ["#####", "#....", "#....", "####.", "#....", "#....", "#...."],
  I: ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "#####"],
  M: ["#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"],
  N: ["#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#"],
  O: [".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."],
  P: ["####.", "#...#", "#...#", "####.", "#....", "#....", "#...."],
  R: ["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"],
  S: [".####", "#....", "#....", ".###.", "....#", "....#", "####."],
  T: ["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."],
  V: ["#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."],
  W: ["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "##.##", "#...#"],
  X: ["#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"],
};

/** The word as rows of lit pixels, top to bottom, one blank column between letters. */
export function bitmap(word: string): boolean[][] {
  const letters = [...word].map((ch) => {
    const glyph = glyphs[ch];
    if (!glyph) throw new Error(`No glyph for "${ch}" in the pixel font`);
    return glyph;
  });
  return Array.from({ length: GLYPH_H }, (_, y) =>
    letters.flatMap((glyph, i) => [...(i > 0 ? Array(GAP).fill(false) : []), ...[...glyph[y]].map((c) => c === "#")]),
  );
}
